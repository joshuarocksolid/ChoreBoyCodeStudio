"""Write the Qt signal table the code generator checks connections against.

Run under FreeCAD 1.1's PySide6 with QT_QPA_PLATFORM=offscreen::

    python tools/form_builder/dump_qt_signals.py

It rewrites ``app/features/form_builder/engine/codegen/qt_signals.py``.
``tests/form_builder/engine/codegen/test_qt_signals.py`` compares the table with
the running Qt and fails naming the class and signal. ``--json`` prints the
live table instead of writing the module.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Dict, Optional, Tuple

TARGET = (
    Path(__file__).resolve().parents[2]
    / "app"
    / "features"
    / "form_builder"
    / "engine"
    / "codegen"
    / "qt_signals.py"
)

_HEADER = '''"""Signals each Qt class declares, for checking ``<connection>`` elements.

Generated by ``tools/form_builder/dump_qt_signals.py`` from PySide6 %s. Do not edit.
Each entry is ``class: (super class, own signal names)``. Covers every QObject
class in QtWidgets plus the QtGui and QtCore classes a form can hold.
"""

from __future__ import annotations

from typing import Dict, FrozenSet, Optional, Tuple

QT_VERSION = %r

_TABLE: Dict[str, Tuple[Optional[str], Tuple[str, ...]]] = {
'''

_FOOTER = '''}


def known_class(class_name: str) -> bool:
    """True when the table lists ``class_name``."""
    return class_name in _TABLE


def signal_names(class_name: str) -> Optional[FrozenSet[str]]:
    """Every signal name ``class_name`` has, inherited ones included.

    None when the class is not in the table.
    """
    if class_name not in _TABLE:
        return None
    found = set()
    current: Optional[str] = class_name
    seen = set()
    while current is not None and current not in seen and current in _TABLE:
        seen.add(current)
        parent, own = _TABLE[current]
        found.update(own)
        current = parent
    return frozenset(found)
'''


def live_table() -> Dict[str, Tuple[Optional[str], Tuple[str, ...]]]:
    """``class: (super, own signal names)`` read from the running PySide6."""
    from PySide6 import QtCore, QtGui, QtWidgets
    from PySide6.QtCore import QMetaMethod, QObject

    classes = []
    for name in dir(QtWidgets):
        value = getattr(QtWidgets, name)
        # QtWidgets also re-exports a few QtGui classes once QtGui is loaded.
        if (
            isinstance(value, type)
            and issubclass(value, QObject)
            and value.__module__ == QtWidgets.__name__
        ):
            classes.append(value)
    for value in (QtGui.QAction, QtGui.QActionGroup, QtCore.QObject):
        classes.append(value)
    table: Dict[str, Tuple[Optional[str], Tuple[str, ...]]] = {}
    pending = list(classes)
    while pending:
        cls = pending.pop()
        meta = cls.staticMetaObject
        name = meta.className()
        if name in table:
            continue
        parent_meta = meta.superClass()
        parent = parent_meta.className() if parent_meta is not None else None
        own = []
        for index in range(meta.methodOffset(), meta.methodCount()):
            method = meta.method(index)
            if method.methodType() != QMetaMethod.MethodType.Signal:
                continue
            signal = bytes(method.name().data()).decode()
            if signal not in own:
                own.append(signal)
        table[name] = (parent, tuple(sorted(own)))
        if parent is not None and parent not in table:
            for base in cls.__mro__[1:]:
                base_meta = getattr(base, "staticMetaObject", None)
                if base_meta is not None and base_meta.className() == parent:
                    pending.append(base)
                    break
    return table


def render(table: Dict[str, Tuple[Optional[str], Tuple[str, ...]]], qt_version: str) -> str:
    lines = [_HEADER % (qt_version, qt_version)]
    for name in sorted(table):
        parent, own = table[name]
        lines.append("    %r: (%r, %r),\n" % (name, parent, own))
    lines.append(_FOOTER)
    return "".join(lines)


def main() -> int:
    from PySide6 import QtCore

    if sys.argv[1:] == ["--json"]:
        # The table test reads this in a fresh interpreter.
        payload = {"qt_version": QtCore.qVersion(), "classes": live_table()}
        print(json.dumps(payload, sort_keys=True))
        return 0
    TARGET.write_text(render(live_table(), QtCore.qVersion()), encoding="utf-8")
    print("wrote %s" % TARGET)
    return 0


if __name__ == "__main__":
    sys.exit(main())
