"""Write two generated pages of the form builder manual.

``docs/manual/form_builder/keyboard.md`` lists every form designer shortcut.
``docs/manual/form_builder/diagnostics.md`` lists every problem code a person
can see. Both pages are rendered from the registries the editor uses, so a
hand edit would drift. The unit test compares the files to this output.

Loading the shortcut table imports Qt. Run the writer with FreeCAD's Python:

    CBCS_APPRUN=~/opt/freecad/AppRun python3 -c "import runpy; runpy.run_path('tools/form_builder_user_manual.py', run_name='__main__')"

The test command is the same runtime, through ``run_tests.py``.
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import Iterable, List, Sequence, Tuple

REPO_ROOT = Path(__file__).resolve().parents[1]
MANUAL_DIR = REPO_ROOT / "docs" / "manual" / "form_builder"
KEYBOARD_PATH = MANUAL_DIR / "keyboard.md"
DIAGNOSTICS_PATH = MANUAL_DIR / "diagnostics.md"

_GENERATED = "Generated by `tools/form_builder_user_manual.py`. Do not edit by hand."


def _repo_on_path() -> None:
    root = str(REPO_ROOT)
    if root not in sys.path:
        sys.path.insert(0, root)


def _cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def _plain_where(text: str) -> str:
    """Turn a focus-host id the keys page leaves raw into words.

    ``where_words`` already names the hosts it knows. A later host such as
    ``behavior_list`` would otherwise be printed as an internal id.
    """
    parts: List[str] = []
    for part in text.split(", "):
        if "_" not in part:
            parts.append(part)
            continue
        words = part.split("_")
        parts.append(" ".join([words[0].capitalize()] + [word.lower() for word in words[1:]]))
    return ", ".join(parts)


def _table(headers: Sequence[str], rows: Iterable[Sequence[str]]) -> str:
    head = "| " + " | ".join(headers) + " |"
    rule = "| " + " | ".join("---" for _ in headers) + " |"
    body = ["| " + " | ".join(_cell(cell) for cell in row) + " |" for row in rows]
    return "\n".join([head, rule] + body)


def keyboard_pairs() -> Tuple[Tuple[str, str], ...]:
    """``(shortcut, label)`` for every bound form key, including inert shell keys."""
    _repo_on_path()
    from app.features.form_builder.engine.shell_commands import INERT_SHORTCUTS, INERT_STATUS
    from app.features.form_builder.integration.keys_ext import all_commands

    pairs = [(command.shortcut, command.label) for command in all_commands() if command.shortcut]
    pairs.extend((key, INERT_STATUS) for key in INERT_SHORTCUTS)
    return tuple(pairs)


def keyboard_markdown() -> str:
    """The keyboard page, including every pair from ``keyboard_pairs``."""
    _repo_on_path()
    from app.features.form_builder.integration.keys_ext import all_commands
    from app.features.form_builder.qtside.keys_page.model import DESIGNER_GROUP, build_groups

    commands = all_commands()
    by_id = {command.command_id: command.shortcut for command in commands}
    go_to = by_id.get("form.action.goToWidget", "")
    preview = by_id.get("form.action.preview", "")
    lines = [
        "# Keyboard reference",
        "",
        _GENERATED,
        "",
        "These are the form designer keys. Open `File > Settings... > Keybindings` and look under Form designer to change one.",
        "",
    ]
    if go_to and preview:
        lines.append(
            "Press %s to go to a widget. Press %s to open Preview. "
            "Run behavior starts checked. When the form has checks, steps, or rules, "
            "Preview runs them and undoes database changes. Uncheck Run behavior to see the layout only."
            % (go_to, preview)
        )
        lines.append("")
    lines.append("The full task pages start at [the form builder manual](index.md).")
    lines.append("")
    for group in build_groups(commands, {}):
        if group.title == DESIGNER_GROUP:
            continue
        lines.append("## %s" % group.title)
        lines.append("")
        rows = [(row.keys, row.what, _plain_where(row.where)) for row in group.rows if row.keys]
        lines.append(_table(("Keys", "What it does", "Where"), rows))
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def visible_codes() -> Tuple[str, ...]:
    """Problem codes the Problems panel can show, in code order.

    FB901 through FB999 are reserved for internal diagnostics and are left out.
    """
    _repo_on_path()
    from app.features.form_builder.engine.diagnostic_codes import discover
    from app.features.form_builder.engine.diagnostics import CODES

    discover()
    shown = [code for code in CODES if int(code[2:]) < 900]
    return tuple(sorted(shown))


def _what_to_do(blocks_open: bool, severity: str) -> str:
    if blocks_open:
        return "Design will not open this form until you fix it. You can still open the file as text."
    if severity == "error":
        return "Fix this before you rely on the form. You can still save."
    if severity == "warning":
        return "The form still opens. Fix this when you can."
    return "Nothing is broken. Read the note and decide whether to change anything."


def diagnostics_markdown() -> str:
    """One row per visible problem code, using the registry title."""
    _repo_on_path()
    from app.features.form_builder.engine.diagnostic_codes import discover
    from app.features.form_builder.engine.diagnostics import CODES

    discover()
    kind_word = {"error": "Error", "warning": "Warning", "info": "Info"}
    codes = visible_codes()
    blocked = sum(1 for code in codes if CODES[code].blocks_visual_open)
    blocked_noun = "error" if blocked == 1 else "errors"
    blocked_verb = "stops" if blocked == 1 else "stop"
    rows = []
    for code in codes:
        info = CODES[code]
        rows.append(
            (
                code,
                kind_word.get(info.severity.value, info.severity.value),
                info.title,
                _what_to_do(info.blocks_visual_open, info.severity.value),
            )
        )
    lines = [
        "# Form problems",
        "",
        _GENERATED,
        "",
        "The Problems panel can show these codes while you work on a form. The filters on that panel are Errors, Warnings, and Info.",
        "",
        "The title is the short text stored for the code. A longer sentence in the panel may add the widget name. Square brackets in a title name a button on that problem, such as [Read now].",
        "",
        "A name the designer refuses while you type is shown on the name box. Those refusals are not in this table.",
        "",
        "Saving a form is still allowed when a code is an error. %d %s %s Design from opening the form. The last column says so."
        % (blocked, blocked_noun, blocked_verb),
        "",
        _table(("Code", "Kind", "Title", "What to do"), rows),
        "",
        "More tasks are in [the form builder manual](index.md).",
        "",
    ]
    return "\n".join(lines)


def write_pages() -> None:
    MANUAL_DIR.mkdir(parents=True, exist_ok=True)
    KEYBOARD_PATH.write_text(keyboard_markdown(), encoding="utf-8")
    DIAGNOSTICS_PATH.write_text(diagnostics_markdown(), encoding="utf-8")


def main() -> None:
    write_pages()
    print(KEYBOARD_PATH.relative_to(REPO_ROOT))
    print(DIAGNOSTICS_PATH.relative_to(REPO_ROOT))


if __name__ == "__main__":
    main()
