"""What the Insert pane is given by the workbench. Qt-free protocols; no integration imports here."""

from __future__ import annotations

from typing import Any, Dict, Optional, Protocol, Sequence, Tuple


class InsertMemoryPort(Protocol):
    """Per-user Insert state (UX-CAT-004, -005, -006)."""

    def recent(self) -> Tuple[str, ...]: ...

    def note_used(self, key: str) -> None: ...

    def clear_recent(self) -> None: ...

    def view(self) -> str: ...

    def set_view(self, view: str) -> None: ...

    def expanded_states(self) -> Dict[str, bool]: ...

    def set_expanded(self, category: str, expanded: bool) -> None: ...


class PieceOps(Protocol):
    """Saved-piece logic that lives with the settings store (integration side)."""

    def renamed(self, pieces: Sequence[Any], index: int, name: str) -> Tuple[Any, ...]: ...

    def without(self, pieces: Sequence[Any], index: int) -> Tuple[Any, ...]: ...

    def for_ids(self, document: Any, ids: Sequence[Any], taken: Sequence[str]) -> Optional[Any]: ...

    def publish(self, xml: str) -> None: ...
