"""Preview / Try-mode wire protocol, version 1 (CONTRACTS.md section 10).

Pure data and codec. Both the editor (``qtside.preview.pool``) and the child
(``qtside.preview.child``) import this module. Qt-free.

A frame is ``FRAME_PREFIX + json + newline``. ``json`` is
``app.plugins.rpc_protocol.encode_message`` without its trailing newline
(``sort_keys=True``, ASCII). Lines without the prefix are noise. A prefixed
line that is not a known message is a ``ProtocolViolation``. Adding an
optional field does not bump the version. Receivers ignore unknown fields.
A breaking change bumps ``PROTOCOL_VERSION`` and ``FRAME_PREFIX`` together.
"""

from __future__ import annotations

from dataclasses import MISSING, dataclass, fields, is_dataclass
from typing import Any, Dict, List, Literal, Optional, Tuple, Union, get_args, get_origin, get_type_hints

from app.plugins.rpc_protocol import decode_message, encode_message

PROTOCOL_NAME = "cbcs_form_preview"
PROTOCOL_VERSION = 1
FRAME_PREFIX = "\x1eCBFP1 "
#: Frames larger than this are refused by both ends (ProtocolViolation).
MAX_FRAME_BYTES = 32 * 1024 * 1024

_Decoded = Union["HostMessage", "ChildMessage", "NoiseLine", "ProtocolViolation"]


