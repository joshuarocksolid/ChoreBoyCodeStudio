_HINTS: Dict[type, Dict[str, Any]] = {}


def _hints(cls: type) -> Dict[str, Any]:
    cached = _HINTS.get(cls)
    if cached is None:
        cached = get_type_hints(cls)
        _HINTS[cls] = cached
    return cached


def _to_jsonable(value: object) -> object:
    if value is None or isinstance(value, (str, int, float, bool)):
        return value
    if isinstance(value, tuple):
        return [_to_jsonable(item) for item in value]
    if isinstance(value, list):
        return [_to_jsonable(item) for item in value]
    if isinstance(value, dict):
        return {str(key): _to_jsonable(item) for key, item in value.items()}
    if is_dataclass(value):
        payload = {}
        for field in fields(value):
            payload[field.name] = _to_jsonable(getattr(value, field.name))
        return payload
    raise TypeError("preview frame value %r is not JSON" % (type(value).__name__,))


def encode_frame(message: Union[HostMessage, ChildMessage]) -> str:
    """``FRAME_PREFIX + json + newline``, pure ASCII, deterministic key order."""
    body = encode_message(_to_jsonable(message)).rstrip("\n")  # type: ignore[arg-type]
    frame = FRAME_PREFIX + body + "\n"
    encoded = frame.encode("ascii")
    if len(encoded) > MAX_FRAME_BYTES:
        raise ValueError("preview frame exceeds %s bytes" % (MAX_FRAME_BYTES,))
    return frame


def _decode_value(hint: Any, value: object) -> object:
    if hint is object or hint is Any:
        return value
    origin = get_origin(hint)
    if origin is Literal:
        if value not in get_args(hint):
            raise ValueError("unexpected value %r" % (value,))
        return value
    if origin is Union:
        args = get_args(hint)
        if value is None and type(None) in args:
            return None
        inners = [arg for arg in args if arg is not type(None)]
        if len(inners) == 1:
            return _decode_value(inners[0], value)
        errors: List[str] = []
        for inner in inners:
            try:
                return _decode_value(inner, value)
            except (TypeError, ValueError) as exc:
                errors.append(str(exc))
        raise ValueError("union mismatch: %s" % "; ".join(errors))
    if origin in (tuple, Tuple):
        if not isinstance(value, list):
            raise ValueError("expected a list")
        args = get_args(hint)
        if len(args) == 2 and args[1] is Ellipsis:
            return tuple(_decode_value(args[0], item) for item in value)
        if len(args) != len(value):
            raise ValueError("tuple length")
        return tuple(_decode_value(arg, item) for arg, item in zip(args, value))
    if origin in (dict, Dict):
        if not isinstance(value, dict):
            raise ValueError("expected an object")
        key_hint, val_hint = get_args(hint) or (str, object)
        return {_decode_value(key_hint, key): _decode_value(val_hint, item) for key, item in value.items()}
    if hint is str:
        if not isinstance(value, str):
            raise ValueError("expected a string")
        return value
    if hint is int:
        if isinstance(value, bool) or not isinstance(value, int):
            raise ValueError("expected an int")
        return value
    if hint is float:
        if isinstance(value, bool) or not isinstance(value, (int, float)):
            raise ValueError("expected a float")
        return float(value)
    if hint is bool:
        if not isinstance(value, bool):
            raise ValueError("expected a bool")
        return value
    if is_dataclass(hint):
        if not isinstance(value, dict):
            raise ValueError("expected an object")
        return _decode_into(hint, value)
    raise ValueError("unsupported frame type %s" % (hint,))


def _decode_into(cls: type, data: Dict[str, object]) -> object:
    kwargs: Dict[str, object] = {}
    for name, hint in _hints(cls).items():
        if name not in data:
            field = next(item for item in fields(cls) if item.name == name)
            if field.default is MISSING and field.default_factory is MISSING:
                raise ValueError("missing %s" % name)
            continue
        kwargs[name] = _decode_value(hint, data[name])
    return cls(**kwargs)


def _decode_payload(payload: Dict[str, object]) -> Union[HostMessage, ChildMessage]:
    kind = payload.get("type")
    if not isinstance(kind, str):
        raise ValueError("missing type")
    cls = _MESSAGE_TYPES.get(kind)
    if cls is None:
        raise ValueError("unknown type %s" % kind)
    return _decode_into(cls, payload)  # type: ignore[return-value]


def decode_line(line: str, *, stream: str = "stdout") -> _Decoded:
    """Never raises. A partial line is not passed here. See :class:`FrameDecoder`."""
    if line.endswith("\r"):
        line = line[:-1]
    if not line.startswith(FRAME_PREFIX):
        return NoiseLine(stream=stream, text=line)
    raw = line.encode("utf-8", "replace")
    if len(raw) > MAX_FRAME_BYTES:
        return ProtocolViolation(line=line[:200], reason="frame exceeds 32MB")
    body = line[len(FRAME_PREFIX) :]
    try:
        body.encode("ascii")
    except UnicodeEncodeError:
        return ProtocolViolation(line=line[:200], reason="frame is not ASCII")
    try:
        payload = decode_message(body)
    except (TypeError, ValueError):
        return ProtocolViolation(line=line[:200], reason="frame is not a JSON object")
    try:
        return _decode_payload(payload)
    except (TypeError, ValueError) as exc:
        return ProtocolViolation(line=line[:200], reason=str(exc))


class FrameDecoder:
    """Assembles stdout chunks into frames. A chunk may split a line."""

    def __init__(self) -> None:
        self._pending = ""

    def feed(self, text: str, *, stream: str = "stdout") -> Tuple[_Decoded, ...]:
        self._pending += text
        if len(self._pending.encode("utf-8", "replace")) > MAX_FRAME_BYTES:
            self._pending = ""
            return (ProtocolViolation(line="", reason="frame exceeds 32MB"),)
        found: List[_Decoded] = []
        while "\n" in self._pending:
            line, self._pending = self._pending.split("\n", 1)
            found.append(decode_line(line, stream=stream))
        return tuple(found)

    @property
    def pending(self) -> str:
        """Bytes held back because they have no newline yet."""
        return self._pending


def is_mutation(message: object) -> bool:
    """True for the one in-flight LoadForm or UpdateForm a view may have."""
    return isinstance(message, (LoadForm, UpdateForm))
