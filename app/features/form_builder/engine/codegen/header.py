"""Generated-file banner and hashes (CONTRACTS.md section 9.2)."""

from __future__ import annotations

import hashlib
import re
from typing import Optional, Tuple

from app.features.form_builder.engine.codegen.api_types import CODEGEN_VERSION, GeneratedHeader

_FROM_LINE = re.compile(
    r"^## Generated from (.+) by ChoreBoy Code Studio\. Do not edit this file:$"
)
_WINDOW_LINE = re.compile(r"^## (.+)\.$")
_LOGIC_LEAD = "## The behaviour below (rules, checks, data) runs only through this file."

_BORDER = "#" * 80


def render_header(
    *,
    ui_file_name: str,
    window_file_name: str,
    has_logic: bool,
    source_sha256: Optional[str],
    body_sha256: str,
) -> str:
    """The ui module banner, ending with a newline."""
    lines = [
        "# -*- coding: utf-8 -*-",
        _BORDER,
        "## Generated from %s by ChoreBoy Code Studio. Do not edit this file:" % ui_file_name,
        "## it is rewritten every time the form is saved. Put your code in",
        "## %s." % window_file_name,
    ]
    if has_logic:
        lines.append("## The behaviour below (rules, checks, data) runs only through this file.")
        lines.append(
            "## Loading %s with QUiLoader gives the layout without the behaviour." % ui_file_name
        )
    lines.append("## cbcs-codegen: %s" % CODEGEN_VERSION)
    if source_sha256 is not None:
        lines.append("## cbcs-source-sha256: %s" % source_sha256)
    lines.append("## cbcs-body-sha256: %s" % body_sha256)
    lines.append(_BORDER)
    return "\n".join(lines) + "\n"


def render_resource_header(*, qrc_file_name: str, body_sha256: str) -> str:
    """Banner for ``*_rc.py``. Same machine lines, no window file."""
    lines = [
        "# -*- coding: utf-8 -*-",
        _BORDER,
        "## Generated from %s by ChoreBoy Code Studio. Do not edit this file:" % qrc_file_name,
        "## it is rewritten every time the resources change.",
        "## cbcs-codegen: %s" % CODEGEN_VERSION,
        "## cbcs-body-sha256: %s" % body_sha256,
        _BORDER,
    ]
    return "\n".join(lines) + "\n"


def split_generated(text: str) -> Optional[Tuple[str, str]]:
    """``(header, body)`` split on the closing hash border. None when the banner is missing."""
    marker = _BORDER + "\n"
    first = text.find(marker)
    if first < 0:
        return None
    second = text.find(marker, first + len(marker))
    if second < 0:
        return None
    cut = second + len(marker)
    return text[:cut], text[cut:]


def read_header(text: str) -> Optional[GeneratedHeader]:
    """Parse the banner. None when it is missing or malformed."""
    if not text.startswith("# -*- coding: utf-8 -*-\n"):
        return None
    parts = split_generated(text)
    if parts is None:
        return None
    header, _body = parts
    version: Optional[int] = None
    source: Optional[str] = None
    body_hash: Optional[str] = None
    saw_source = False
    for line in header.splitlines():
        if line.startswith("## cbcs-codegen:"):
            raw = line.split(":", 1)[1].strip()
            if not raw.isdigit():
                return None
            version = int(raw)
        elif line.startswith("## cbcs-source-sha256:"):
            saw_source = True
            source = line.split(":", 1)[1].strip() or None
        elif line.startswith("## cbcs-body-sha256:"):
            body_hash = line.split(":", 1)[1].strip() or None
    if version is None or not body_hash:
        return None
    if not saw_source:
        source = None
    return GeneratedHeader(codegen_version=version, source_sha256=source, body_sha256=body_hash)


def _banner_fields(header: str) -> Optional[Tuple[str, str, bool, bool]]:
    """``(ui file, window file, has_logic, resource)`` or None when the banner isn't ours.

    ``resource`` is a ``*_rc.py`` banner, which has no window file.
    """
    lines = header.splitlines()
    if len(lines) < 6 or lines[0] != "# -*- coding: utf-8 -*-":
        return None
    if lines[1] != _BORDER or lines[-1] != _BORDER:
        return None
    found = _FROM_LINE.fullmatch(lines[2])
    if found is None:
        return None
    ui_name = found.group(1)
    if lines[3] == "## it is rewritten every time the resources change.":
        return ui_name, "", False, True
    if lines[3] != "## it is rewritten every time the form is saved. Put your code in":
        return None
    window = _WINDOW_LINE.fullmatch(lines[4])
    if window is None:
        return None
    has_logic = len(lines) > 5 and lines[5] == _LOGIC_LEAD
    return ui_name, window.group(1), has_logic, False


def is_hand_edited(text: str) -> bool:
    """True unless the banner is exactly the one ``render_header`` would write for its fields.

    A body-hash mismatch is an edit. So is any banner line that isn't part of that rebuild,
    including a statement inserted above the border. A CRLF file does not match the LF banner.
    """
    parsed = read_header(text)
    if parsed is None:
        return True
    parts = split_generated(text)
    if parts is None:
        return True
    header, body = parts
    if hashlib.sha256(body.encode("utf-8")).hexdigest() != parsed.body_sha256:
        return True
    if any(not line.startswith("#") for line in header.splitlines()):
        return True
    fields = _banner_fields(header)
    if fields is None:
        return True
    ui_name, window_name, has_logic, resource = fields
    if resource:
        rebuilt = render_resource_header(qrc_file_name=ui_name, body_sha256=parsed.body_sha256)
    else:
        rebuilt = render_header(
            ui_file_name=ui_name,
            window_file_name=window_name,
            has_logic=has_logic,
            source_sha256=parsed.source_sha256,
            body_sha256=parsed.body_sha256,
        )
    return header != rebuilt


def is_stale(text: str, ui_bytes: bytes) -> bool:
    """True when the source hash or the codegen version does not match."""
    parsed = read_header(text)
    if parsed is None:
        return True
    if parsed.codegen_version != CODEGEN_VERSION:
        return True
    source = hashlib.sha256(ui_bytes).hexdigest()
    return parsed.source_sha256 != source
