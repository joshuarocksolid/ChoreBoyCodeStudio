"""Read the banner Code Studio writes at the top of generated Python files.

The grammar is CONTRACTS.md section 9.2. It is duplicated from the form
builder's codegen header because the editor must not import the feature. A
contract test renders banners with codegen and reads them back here.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from typing import Collection, Literal, Optional

GeneratedKind = Literal["module", "resource"]

_CODING = "# -*- coding: utf-8 -*-"
_BORDER = "#" * 80
_FROM_LINE = re.compile(r"^## Generated from (.+) by ChoreBoy Code Studio\. Do not edit this file:$")
_MODULE_LINE = "## it is rewritten every time the form is saved. Put your code in"
_RESOURCE_LINE = "## it is rewritten every time the resources change."
_WINDOW_LINE = re.compile(r"^## (.+)\.$")


@dataclass(frozen=True)
class GeneratedBanner:
    """What a generated file says it was made from. ``window_name`` is empty for resources."""

    kind: GeneratedKind
    source_name: str
    window_name: str


@dataclass(frozen=True)
class GeneratedLock:
    """A tab showing a generated file. ``edit_anyway`` is the user's choice for this tab only."""

    banner: GeneratedBanner
    edit_anyway: bool = False


def read_generated_banner(text: str) -> Optional[GeneratedBanner]:
    """The banner at the top of ``text``, or None when the file is not generated.

    Only the identifying lines are read, so a file whose body or hashes were
    edited by hand still reads as generated.
    """
    lines = text.splitlines()[:5]
    if len(lines) < 4 or lines[0] != _CODING or lines[1] != _BORDER:
        return None
    found = _FROM_LINE.match(lines[2])
    if found is None:
        return None
    source_name = found.group(1)
    if lines[3] == _RESOURCE_LINE:
        return GeneratedBanner(kind="resource", source_name=source_name, window_name="")
    if lines[3] != _MODULE_LINE or len(lines) < 5:
        return None
    window = _WINDOW_LINE.match(lines[4])
    if window is None:
        return None
    return GeneratedBanner(kind="module", source_name=source_name, window_name=window.group(1))


def generated_bar_text(lock: GeneratedLock) -> str:
    banner = lock.banner
    if lock.edit_anyway:
        if banner.kind == "resource":
            return "Edits here are replaced the next time %s changes." % banner.source_name
        return "Edits here are replaced the next time %s is saved." % banner.source_name
    if banner.kind == "resource":
        return (
            "Generated from %s. Code Studio rewrites this file every time the resources change."
            % banner.source_name
        )
    return (
        "Generated from %s. Code Studio rewrites this file every time the form is saved. "
        "Put your code in %s." % (banner.source_name, banner.window_name)
    )


def generated_sibling(name: str, sibling_names: Collection[str]) -> Optional[str]:
    """The source file ``name`` is generated from when that source sits beside it.

    Decided by name alone so the project tree needs no file reads.
    """
    if name.startswith("ui_") and name.endswith(".py"):
        source = name[len("ui_") : -len(".py")] + ".ui"
    elif name.endswith("_rc.py"):
        source = name[: -len("_rc.py")] + ".qrc"
    else:
        return None
    if source in (".ui", ".qrc") or source not in sibling_names:
        return None
    return source
